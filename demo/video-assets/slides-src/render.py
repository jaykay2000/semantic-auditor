"""Render the video slides to PNG (1920x1080 CSS px, device scale 2 -> 3840x2160).

    python3 slides-src/render.py              # every scene
    python3 slides-src/render.py s01 s08      # only scenes whose name starts with these prefixes

Each slides-src/<name>.html becomes scenes/<name>.png. Every scenes-data/*.json is injected before the page
loads as window.DATA["<file stem>"], so a data-driven slide (s7-b3b-overlap reads DATA["overlap"]) is
regenerated by editing its JSON and re-running this command. Network is blocked: only file:// loads.
The script also reports any element that spills outside the 1920x1080 frame or clips its own text.
"""
import json
import pathlib
import sys

from playwright.sync_api import sync_playwright

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / 'scenes'
DATA_DIR = ROOT / 'scenes-data'

CHECK = """() => {
  const bad = [];
  for (const el of document.querySelectorAll('body *')) {
    const cs = getComputedStyle(el);
    if (cs.display === 'none' || cs.visibility === 'hidden') continue;
    const r = el.getBoundingClientRect();
    if (!r.width || !r.height) continue;
    if (el.closest('[data-crop]') && !el.hasAttribute('data-crop')) continue;  // deliberately cropped by its frame
    const name = el.tagName.toLowerCase() + (el.className && typeof el.className === 'string' ? '.' + el.className.split(' ').join('.') : '');
    if (r.right > 1920.5 || r.bottom > 1080.5 || r.left < -0.5 || r.top < -0.5)
      bad.push(`outside frame: ${name} [${Math.round(r.left)},${Math.round(r.top)},${Math.round(r.right)},${Math.round(r.bottom)}]`);
    if (el.dataset.noclip === undefined && (el.scrollWidth > el.clientWidth + 1 || el.scrollHeight > el.clientHeight + 1)
        && ['hidden', 'clip'].includes(cs.overflow) && el.children.length === 0)
      bad.push(`clips its text: ${name}`);
  }
  return bad;
}"""


def main(argv):
    data = {p.stem: json.loads(p.read_text()) for p in sorted(DATA_DIR.glob('*.json'))}
    pages = sorted(HERE.glob('s*.html'))
    if argv:
        pages = [p for p in pages if any(p.stem.startswith(a) for a in argv)]
    if not pages:
        sys.exit(f'no slide matches {argv}')
    OUT.mkdir(exist_ok=True)
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        for page_path in pages:
            pg = browser.new_page(viewport={'width': 1920, 'height': 1080}, device_scale_factor=2)
            errs = []
            pg.on('pageerror', lambda e, errs=errs: errs.append(str(e)))
            pg.on('console', lambda m, errs=errs: m.type == 'error' and errs.append(m.text))
            pg.route('**/*', lambda r: r.continue_() if r.request.url.startswith('file://') else r.abort())
            pg.add_init_script(f'window.DATA = {json.dumps(data)};')
            pg.goto(page_path.as_uri())
            pg.evaluate('document.fonts.ready')
            pg.wait_for_timeout(150)
            problems = pg.evaluate(CHECK)
            out = OUT / f'{page_path.stem}.png'
            pg.screenshot(path=str(out))
            print(f'{out.name}: errors={errs or "none"} layout={problems or "ok"}')
            pg.close()
        browser.close()


if __name__ == '__main__':
    main(sys.argv[1:])
